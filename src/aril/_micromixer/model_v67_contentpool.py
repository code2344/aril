# Adapted from MicroMixer-4 (Apache-2.0): package imports were adjusted.
"""MicroMixer-4 V67 ContentPoolMixer -- V59 + Multi-Head Saliency Content Pool.

V67 keeps the ENTIRE V59 stack (paper-faithful OAMixer mask on frozen
byte-identity labels + learned scalar saliency, selectivity-difference) and adds
one new path per ReMixerLayer: a **multi-head saliency content pool** that
builds an order-invariant summary of the prefix and re-injects it at every
position as a format-invariant retrieval key.

== Motivation: V59's fundamental problem ==

V59 is the best generaliser (10k paraphrase EM 8/200) but its routing has two
structural blind spots, documented in V59_README / analyze_v59 logs:

  1. The mask M = exp(-kappa * dist) is computed from FROZEN byte-identity
     labels, so M_ij depends only on the byte TYPES at positions i, j — never
     on the actual content. It is a static 256x256 byte-affinity kernel. It
     cannot express "these two questions ask the same thing".
  2. The only content-dependent, format-robust signal is the scalar saliency
     gate — one scalar per position. Every mixing operator (causal conv,
     byte-mask gather) is position- and surface-sensitive; the only global
     aggregation is the uniform causal average, which is content-blind.

Consequence: the retrieval key that maps a question to a memorised answer
entangles surface phrasing with content. On an unseen phrasing the key is
wrong from the FIRST answer word (FT 18%) and the error compounds (EM 4%),
with cross-contamination between similar memorised answers.

The fix must let the model aggregate WHAT was said independently of HOW it was
phrased. Two paraphrases share the same content bytes (entity names, content
words); a saliency-weighted POOL over the prefix is invariant to word order
and function-word changes, so it yields a phrasing-invariant summary.

== Mechanism (per ReMixerLayer, added on top of V59) ==

    h = norm_r(x)                                        # (B, S, D)  (as V59)
    S = sigmoid(pool_proj(h))                            # (B, S, K) — K importance maps
    S <- S * (1 - answer_region(input_ids))              # v2: freeze at last "Assistant: "
    c_k(t) = sum_{j<=t} S_jk * h_j / sum_{j<=t} S_jk     # causal weighted mean / head
    c = mean_k(c_k)                                      # (B, S, D)
    delta_pool = pool_up(GELU(pool_down(c)))             # low-rank adapter, up zero-init
    return x + delta + delta_pool                        # delta = V59 selectivity-difference

== v2: Question-anchored frozen pool ==

V67-v1 (plain cumulative pool) FAILED the 10k paraphrase experiment
(EM 6/200 < V59 8/200) despite the best teacher-forcing val_loss of the
ReMixer line (0.3327). Qualitative inspection showed a failure mode V59
never had: runaway degeneration ("!!!!", "zzzz") and cross-answer
contamination cascades. Root cause: during generation the pool ACCUMULATES
the model's own generated bytes; the first wrong byte pollutes the summary,
which biases the next prediction toward the pollution — a positive
feedback loop. Teacher-forcing never sees this (true prefixes), hence the
val_loss vs generation EM inversion.

v2 fix: the pool STOPS accumulating at the last complete "Assistant: "
marker (a deterministic function of the input bytes, detected per forward
— no learned components, no new parameters). Consequences:

  * The retrieval key is FROZEN at prompt end: answer positions read ONLY
    a summary of the question/prompt region. Generation errors can no
    longer contaminate the key.
  * Still causal and stationary: the mask is a prefix-deterministic byte
    pattern; past values never change as generation continues.
  * Falls back to v1 cumulative behaviour when no marker exists
    (non-dialogue text), so pretraining is unaffected in structure.
  * Multi-turn data: "last complete marker <= t" makes the pool cover all
    prior turns plus the current question — a conversation-state summary.

Properties:

  * ORDER-INVARIANT: the pool is a weighted SET aggregation over prefix
    positions. Permuting question words changes the pool only through the
    saliency maps, not through position.
  * STATIONARY (V66 Stationarity Principle): c(t) is a deterministic function
    of the prefix bytes 1..t (a cumulative mean). During byte-level AR
    generation, past pool values never change as new bytes are generated —
    same family as the uniform cumsum average V59 already computes.
  * SOFT (V60 lesson): pool weights are sigmoid gates in (0,1), no sparsity.
  * FULL-DIM VALUES (V64/V65 lesson): the pool carries full 128-d h vectors;
    the low-rank adapter only transforms the injected delta, it does not
    bottleneck the gathered values of the main stream.
  * BIT-IDENTICAL AT INIT: pool_up is zero-initialised, so delta_pool = 0
    exactly at init; V67 == V59 == V46-3 at initialisation (kappa=0).
  * GRADIENT UNLOCK ORDER: dL/d(pool_up) != 0 from step 1 (GELU(pool_down(c))
    is non-zero with xavier pool_down). pool_down / pool_proj gradients are
    blocked by the zero up-projection at step 0 and unlock once pool_up moves —
    the same 1-step-delay pattern as V59's saliency at kappa=0.

== Inspiration ==

  * OAMixer (Kang, Mo, Shin, arXiv:2212.06595): the mask/kappa/saliency stack
    is unchanged from V58/V59.
  * REMIXERS (NLU, OpenReview 9FHQHJnRtfL): persistent global memory read by
    every position — V67 realises this WITHOUT the L x L H matrix and WITHOUT
    any content-similarity read: the "memory" is the causal saliency pool.
  * HyperMixer diagnosis (arXiv:2203.03691): static token mixing lacks
    input-dependent weights — the pool adds input-dependent global mixing
    through per-position sigmoid gates only (no QK-style pairwise similarity,
    per the project's no-attention philosophy).

== Parameter overhead ==

Per ReMixerLayer (V67 vs V59), at d=128, K=4, r=16:
  - pool_proj: d*K + K        = 516
  - pool_down: d*r + r        = 2,064
  - pool_up:   r*d + d        = 2,176
  - total per layer           = 4,756   (x7 blocks = 33,292)

V67 total at 1M preset: 962,958 + 33,292 = 996,250 (< 1,000,000).

== Philosophy compliance ==

  1. MLP-Mixer backbone (depthwise token-mix + MLP channel-mix).
  2. Strictly under 1M parameters for every preset.
  3. No attention module, no recurrence, no SSM. The pool uses per-position
     sigmoid gates (same family as V59 saliency / squeeze-excitation) and a
     cumulative mean — NO pairwise content similarity anywhere.
"""

