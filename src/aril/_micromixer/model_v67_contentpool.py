def make_byte_labels(vocab_size: int, label_dim: int, seed: int) -> torch.Tensor:
    gen = torch.Generator()
    gen.manual_seed(seed)
    labels = torch.randn(vocab_size, label_dim, generator=gen)
    labels = F.normalize(labels, dim=-1)
    return labels


# "Assistant: " as raw bytes. The pool stops accumulating after the LAST
# complete occurrence of this marker (question-anchored frozen pool, v2).
_ANSWER_MARKER: tuple = (65, 115, 115, 105, 115, 116, 97, 110, 116, 58, 32)


def answer_region_mask(input_ids: torch.Tensor) -> torch.Tensor:
    """(B, S) bool: True for positions AFTER the last complete "Assistant: "
    marker (i.e. inside the answer region of the current turn).

    Deterministic in the input bytes, causal (a position's flag depends only
    on the prefix up to it), stationary (past flags never change when new
    bytes are appended). All False when the marker never appears.
    """
    B, S = input_ids.shape
    L = len(_ANSWER_MARKER)
    if S < L:
        return torch.zeros(B, S, dtype=torch.bool, device=input_ids.device)
    marker = torch.tensor(_ANSWER_MARKER, device=input_ids.device)
    windows = input_ids.unfold(1, L, 1)                    # (B, S-L+1, L)
    starts = (windows == marker).all(dim=-1)               # (B, S-L+1) window START i
    # Position t is in the answer region iff a marker starts at some i <= t-L
    # (then the marker occupies i..i+L-1 and t >= i+L is after it).
    csum = torch.cumsum(starts.long(), dim=1)              # (B, S-L+1)
    pad = torch.zeros(B, L, dtype=torch.long, device=input_ids.device)
    shifted = torch.cat([pad, csum], dim=1)[:, :S]         # shifted[t] = csum[t-L]
    return shifted > 0


class ReMixerLayer(nn.Module):
    """V67 ReMixer: V59 (OAMixer mask + saliency) + multi-head content pool.

    Three orthogonal mechanisms:
      1. Content mask (fixed byte labels, kappa): WHO mixes with whom.
      2. Saliency (learned Linear(d,1) + sigmoid): HOW MUCH each position
         contributes to the selective gather.
      3. Content pool (K sigmoid importance maps + causal weighted mean +
         zero-init low-rank adapter): an order-invariant, stationary summary
         of the prefix, injected at every position as a format-invariant
         retrieval key.

    Bit-identical to V46-3 at init: delta = 0 at kappa=0 (selectivity-
    difference) and delta_pool = 0 (zero-init pool_up).
    """

    def __init__(
        self,
        d_model: int,
        kappa_init: float = 0.0,
        row_normalize: bool = True,
        pool_heads: int = 4,
        pool_rank: int = 0,
    ):
        super().__init__()
        self.d_model = d_model
        self.row_normalize = row_normalize
        self.pool_heads = pool_heads
        self.pool_rank = pool_rank if pool_rank > 0 else max(4, d_model // 8)

        # --- V59 stack (unchanged) ---
        self.norm = RMSNorm(d_model)
        self.kappa = nn.Parameter(torch.tensor(float(kappa_init)))
        self.saliency_proj = nn.Linear(d_model, 1, bias=True)

        # --- V67 content pool ---
        self.pool_proj = nn.Linear(d_model, pool_heads, bias=True)
        self.pool_down = nn.Linear(d_model, self.pool_rank, bias=True)
        self.pool_up = nn.Linear(self.pool_rank, d_model, bias=True)

    def forward(
        self,
        x: torch.Tensor,
        y_norm: torch.Tensor,
        freeze_mask: torch.Tensor | None = None,
    ) -> torch.Tensor:
        B, S, D = x.shape

        with torch.no_grad():
            self.kappa.clamp_(min=0.0)

        h = self.norm(x)

        # === V59: saliency + content mask + selectivity-difference ===
        saliency = torch.sigmoid(self.saliency_proj(h))  # (B, S, 1) in (0, 1)
        h_sal = h * saliency                             # (B, S, D)

        sim = y_norm @ y_norm.transpose(-1, -2)          # cosine sim [-1, 1]
        dist = 1.0 - sim                                 # [0, 2]
        M = torch.exp(-self.kappa * dist)                # (B, S, S) in (0, 1]

        causal = torch.tril(
            torch.ones(S, S, device=x.device, dtype=torch.bool)
        )
        M = M.masked_fill(~causal, 0.0)

        if self.row_normalize:
            row_sums = M.sum(dim=-1, keepdim=True).clamp(min=1e-8)
            M = M / row_sums

        mixed_selective = M @ h_sal                      # (B, S, D)

        cumsum = torch.cumsum(h_sal, dim=1)
        counts = torch.arange(1, S + 1, device=h.device, dtype=h.dtype)
        mixed_uniform = cumsum / counts.view(1, -1, 1)   # (B, S, D)

        delta = mixed_selective - mixed_uniform

        # === V67: multi-head saliency content pool (question-anchored) ===
        pool_w = torch.sigmoid(self.pool_proj(h))        # (B, S, K) in (0, 1)
        if freeze_mask is not None:
            # Answer-region positions contribute 0: the pool freezes at the
            # last "Assistant: " marker -> generation cannot contaminate it.
            pool_w = pool_w * (~freeze_mask).to(pool_w.dtype).unsqueeze(-1)
        # Causal weighted cumulative mean per head: order-invariant,
        # stationary (function of prefix only), soft, full-dim values.
        num = torch.cumsum(pool_w.unsqueeze(-1) * h.unsqueeze(2), dim=1)  # (B,S,K,D)
        den = torch.cumsum(pool_w, dim=1).clamp(min=1e-4).unsqueeze(-1)   # (B,S,K,1)
        c_pre = num / den                              # (B, S, K, D)
        self.last_pool_pre = c_pre                     # exposed for V69 PCP training
        c = c_pre.mean(dim=2)                          # (B, S, D)
        # Low-rank adapter injection; pool_up is zero-init -> 0 at init.
        delta_pool = self.pool_up(F.gelu(self.pool_down(c)))              # (B,S,D)

        return x + delta + delta_pool

    @property
    def alpha(self) -> torch.Tensor:
        return torch.tensor(1.0)


class ReMixerBlock(nn.Module):
    def __init__(
        self,
        d_model: int,
        kernel_size: int,
        dilation: int,
        expansion_token: int = 2,
        expansion_channel: int = 2,
        kappa_init: float = 0.0,
        row_normalize: bool = True,
        pool_heads: int = 4,
        pool_rank: int = 0,
    ):
        super().__init__()
        self.norm1 = RMSNorm(d_model)
        self.token_mix = CausalDSConv1d(
            d_model, kernel_size, dilation, expansion_token,
        )
        self.norm2 = RMSNorm(d_model)
        self.channel_mix = ChannelMLP(d_model, expansion_channel)
        self.remixer = ReMixerLayer(
            d_model=d_model,
            kappa_init=kappa_init,
            row_normalize=row_normalize,
            pool_heads=pool_heads,
            pool_rank=pool_rank,
        )

    def forward(
        self,
        x: torch.Tensor,
        y_norm: torch.Tensor,
        freeze_mask: torch.Tensor | None = None,
    ) -> torch.Tensor:
        x = x + self.token_mix(self.norm1(x))
        x = x + self.channel_mix(self.norm2(x))
        x = self.remixer(x, y_norm, freeze_mask)
        return x


class MicroMixerV67ContentPool(nn.Module):
    def __init__(self, config: V67Config):
        super().__init__()
        self.config = config
        d = config.d_model

        self.embed = nn.Embedding(config.vocab_size, d)

        byte_labels = make_byte_labels(
            vocab_size=config.vocab_size,
            label_dim=config.label_dim,
            seed=config.label_seed,
        )
        self.register_buffer("byte_labels", byte_labels, persistent=True)

        assert len(config.dilations) == config.num_blocks
        self.blocks = nn.ModuleList([
            ReMixerBlock(
                d_model=d,
                kernel_size=config.kernel_size,
                dilation=dil,
                expansion_token=config.expansion_token,
                expansion_channel=config.expansion_channel,
                kappa_init=config.kappa_init,
                row_normalize=config.row_normalize,
                pool_heads=config.pool_heads,
                pool_rank=config.pool_rank,
            )
            for dil in config.dilations
        ])

        self.out_norm = RMSNorm(d)
        self._init_weights()

    def _init_weights(self) -> None:
        nn.init.normal_(self.embed.weight, mean=0.0, std=0.02)
        for m in self.modules():
            if isinstance(m, nn.Linear):
                nn.init.xavier_uniform_(m.weight)
                if m.bias is not None:
                    nn.init.zeros_(m.bias)
            elif isinstance(m, nn.Conv1d):
                nn.init.kaiming_uniform_(m.weight, a=math.sqrt(5))
                if m.bias is not None:
                    fan_in, _ = nn.init._calculate_fan_in_and_fan_out(m.weight)
                    bound = 1 / math.sqrt(fan_in) if fan_in > 0 else 0
                    nn.init.uniform_(m.bias, -bound, bound)
        for block in self.blocks:
            block.remixer.kappa.data.fill_(float(self.config.kappa_init))
            # Zero-init the pool up-projection: delta_pool = 0 exactly at init
            # (bit-identical to V46-3), while dL/d(pool_up) != 0 from step 1.
            nn.init.zeros_(block.remixer.pool_up.weight)
            nn.init.zeros_(block.remixer.pool_up.bias)

    def forward(
        self,
        input_ids: torch.Tensor,
        q_mask: torch.Tensor | None = None,
        a_mask: torch.Tensor | None = None,
        all_mask: torch.Tensor | None = None,
        targets: torch.Tensor | None = None,
    ) -> tuple[torch.Tensor, torch.Tensor | None, dict]:
        h = self.embed(input_ids)
        y_norm = self.byte_labels[input_ids]
        freeze_mask = answer_region_mask(input_ids)

        for block in self.blocks:
            h = block(h, y_norm, freeze_mask)
        h = self.out_norm(h)
        logits = h @ self.embed.weight.T
        logits = torch.nan_to_num(logits, nan=0.0, posinf=30.0, neginf=-30.0).clamp(-30, 30)

        if targets is None:
            return logits, None, {"token_acc": torch.tensor(0.0, device=input_ids.device)}

        pad = self.config.pad_token_id
        non_pad = (targets != pad).to(torch.float32)

        ce_per_pos = F.cross_entropy(
            logits.reshape(-1, self.config.vocab_size),
            targets.reshape(-1),
            ignore_index=pad,
            reduction="none",
        ).reshape(input_ids.shape)

        denom = non_pad.sum().clamp(min=1)
        loss = (ce_per_pos * non_pad).sum() / denom

        with torch.no_grad():
            pred = logits.argmax(dim=-1)
            acc = ((pred == targets) & non_pad.bool()).float().sum() / denom

        aux = {
            "ce_loss": loss.detach(),
            "ce_unweighted": loss.detach(),
            "main_loss": loss.detach(),
            "token_acc": acc.detach(),
            "loss_weight_mean": torch.tensor(1.0, device=input_ids.device),
        }
        return logits, loss, aux

    @torch.no_grad()
    def generate(
        self,
        input_ids: torch.Tensor,
        q_mask: torch.Tensor | None = None,
        a_mask: torch.Tensor | None = None,
        all_mask: torch.Tensor | None = None,
        *,
        max_new_tokens: int = 100,
        temperature: float = 1.0,
        top_k: int | None = None,
        top_p: float | None = None,
        repetition_penalty: float = 1.0,
        no_repeat_ngram_size: int = 0,
        eos_token_id: int = 2,
    ) -> torch.Tensor:
        device = input_ids.device
        generated = input_ids.clone()

        for _ in range(max_new_tokens):
            logits, _, _ = self.forward(generated, None, None, None, None)
            next_logits = logits[:, -1, :].float()

            if temperature <= 0:
                next_token = next_logits.argmax(dim=-1, keepdim=True)
            else:
                scaled = next_logits / max(temperature, 1e-6)

                if repetition_penalty != 1.0:
                    for b in range(generated.shape[0]):
                        prev = generated[b].tolist()
                        seen = set(prev)
                        for tok_id in seen:
                            if 0 <= tok_id < scaled.shape[-1]:
                                scaled[b, tok_id] /= repetition_penalty

                if no_repeat_ngram_size > 0 and generated.shape[1] >= no_repeat_ngram_size:
                    ngram = generated[:, -no_repeat_ngram_size+1:].tolist()
                    banned_per_batch = []
                    for b in range(generated.shape[0]):
                        seq = generated[b].tolist()
                        banned = set()
                        for i in range(len(seq) - no_repeat_ngram_size + 1):
                            if seq[i:i+no_repeat_ngram_size-1] == ngram[b]:
                                banned.add(seq[i + no_repeat_ngram_size - 1])
                        banned_per_batch.append(banned)
                    for b, banned in enumerate(banned_per_batch):
                        for tok_id in banned:
                            if 0 <= tok_id < scaled.shape[-1]:
                                scaled[b, tok_id] = float("-inf")

                if top_k is not None and top_k > 0:
                    v, _ = torch.topk(scaled, min(top_k, scaled.shape[-1]))
                    threshold = v[:, -1:]
                    scaled = scaled.masked_fill(scaled < threshold, float("-inf"))

                if top_p is not None and 0 < top_p < 1:
                    sorted_logits, sorted_idx = torch.sort(scaled, descending=True, dim=-1)
                    cum_probs = F.softmax(sorted_logits, dim=-1).cumsum(dim=-1)
                    remove = cum_probs > top_p
                    remove[..., 1:] = remove[..., :-1].clone()
                    remove[..., 0] = False
                    sorted_logits = sorted_logits.masked_fill(remove, float("-inf"))
                    scaled = torch.full_like(scaled, float("-inf"))
                    scaled.scatter_(1, sorted_idx, sorted_logits)

                probs = F.softmax(scaled, dim=-1)
                next_token = torch.distributions.Categorical(probs).sample().unsqueeze(-1)

            generated = torch.cat([generated, next_token], dim=1)

            if (next_token == eos_token_id).all():
                break

        return generated


def count_parameters(model: nn.Module) -> int:
    return sum(p.numel() for p in model.parameters() if p.requires_grad)


def _receptive_field(dilations: tuple, kernel_size: int) -> int:
    return sum((kernel_size - 1) * d for d in dilations)


def v67_contentpool_100k() -> V67Config:
    return V67Config(d_model=48, num_blocks=3, dilations=(1, 2, 4), max_seq_len=512)


